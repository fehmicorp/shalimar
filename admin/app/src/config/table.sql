-- ---------------------------------------------------------------------------
-- USER INVITATIONS
-- token_hash stores a hash of the invitation token, never the raw token.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS user_invitations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(255) NOT NULL,
    username VARCHAR(50) DEFAULT NULL,
    role VARCHAR(30) NOT NULL REFERENCES system_roles(name),
    token_hash CHAR(64) NOT NULL UNIQUE,
    invited_by UUID REFERENCES users(id) ON DELETE SET NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ DEFAULT NULL,
    revoked_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_invitations_email
    ON user_invitations (LOWER(email));

CREATE INDEX IF NOT EXISTS idx_user_invitations_expires_at
    ON user_invitations (expires_at);

CREATE INDEX IF NOT EXISTS idx_user_invitations_invited_by
    ON user_invitations (invited_by);

-- ---------------------------------------------------------------------------
-- SECURITY AUDIT
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS security_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    username VARCHAR(50) DEFAULT NULL,
    action VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT DEFAULT NULL,
    ip_address INET DEFAULT NULL,
    user_agent TEXT DEFAULT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    success BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_security_audit_user_id
    ON security_audit (user_id);

CREATE INDEX IF NOT EXISTS idx_security_audit_category
    ON security_audit (category);

CREATE INDEX IF NOT EXISTS idx_security_audit_action
    ON security_audit (action);

CREATE INDEX IF NOT EXISTS idx_security_audit_created_at
    ON security_audit (created_at DESC);

